with check (
  initiated_by_id = auth.uid()
  and status in ('draft','editing','submitted','edit_requested')
);

drop policy if exists studies_admin_delete on public.sscs_studies;
create policy studies_admin_delete on public.sscs_studies
for delete to authenticated
using (public.current_user_is_admin());

