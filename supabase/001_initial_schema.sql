create policy sscs_documents_delete on storage.objects
for delete to authenticated
using (
  bucket_id = 'sscs-documents'
  and (public.can_edit_study(split_part(name, '/', 1)) or public.current_user_is_admin())
);

-- ---------------------------------------------------------------------------
-- Protect fields and workflow transitions for ship officers even if a browser
-- client is tampered with. Terminal officers/admins are governed by their RLS.
-- ---------------------------------------------------------------------------
create or replace function public.enforce_ship_study_update()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $$
begin
  if public.current_user_role() = 'ship_officer' and not public.current_user_is_admin() then
    if new.initiated_by_id is distinct from old.initiated_by_id
       or new.initiated_by_name is distinct from old.initiated_by_name
       or new.initiated_by_role is distinct from old.initiated_by_role
       or new.vessel_id is distinct from old.vessel_id
       or new.vessel_name is distinct from old.vessel_name
       or new.terminal_notes is distinct from old.terminal_notes
       or new.reviewed_by_id is distinct from old.reviewed_by_id
       or new.reviewed_by_name is distinct from old.reviewed_by_name
       or new.approved_at is distinct from old.approved_at then
      raise exception 'Ship officers cannot modify protected study fields';
    end if;

    if not (
      (old.status = 'draft' and new.status in ('draft','submitted'))
      or (old.status = 'editing' and new.status in ('editing','submitted'))
      or (old.status = 'approved' and new.status = 'edit_requested')
    ) then
      raise exception 'Invalid ship-officer study status transition: % -> %', old.status, new.status;
    end if;
  end if;
  return new;
end;
$$;

drop trigger if exists aa_enforce_ship_study_update on public.sscs_studies;
create trigger aa_enforce_ship_study_update
before update on public.sscs_studies
for each row execute function public.enforce_ship_study_update();

-- ---------------------------------------------------------------------------
-- Lightweight audit triggers
-- ---------------------------------------------------------------------------
create or replace function public.audit_profile_change()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $$
begin
  if old.account_status is distinct from new.account_status
     or old.role is distinct from new.role
     or old.is_admin is distinct from new.is_admin then
    insert into public.audit_logs(user_id, action, entity_type, entity_id, details)
    values (
      auth.uid(), 'profile_access_changed', 'profile', new.id::text,
      jsonb_build_object(
        'old_status', old.account_status, 'new_status', new.account_status,
        'old_role', old.role, 'new_role', new.role,
        'old_is_admin', old.is_admin, 'new_is_admin', new.is_admin
      )
    );
  end if;
  new.updated_at := now();
  return new;
end;
$$;

drop trigger if exists profiles_audit_trigger on public.profiles;
create trigger profiles_audit_trigger
before update on public.profiles
for each row execute function public.audit_profile_change();

create or replace function public.audit_study_status_change()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $$
begin
  if old.status is distinct from new.status then
    insert into public.audit_logs(user_id, action, entity_type, entity_id, details)
    values (
      auth.uid(), 'study_status_changed', 'sscs_study', new.id,
      jsonb_build_object('old_status', old.status, 'new_status', new.status, 'vessel_id', new.vessel_id)
    );
  end if;
  new.updated_at := now();
  return new;
end;
$$;

drop trigger if exists studies_audit_trigger on public.sscs_studies;
create trigger studies_audit_trigger
before update on public.sscs_studies
for each row execute function public.audit_study_status_change();

create or replace function public.touch_vessel_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at := now();
  return new;
end;
$$;

drop trigger if exists vessels_touch_trigger on public.vessels;
create trigger vessels_touch_trigger
before update on public.vessels
for each row execute function public.touch_vessel_updated_at();

