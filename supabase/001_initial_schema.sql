for update to authenticated
using (
  bucket_id = 'sscs-documents'
  and public.can_edit_study(split_part(name, '/', 1))
)
with check (
  bucket_id = 'sscs-documents'
  and public.can_edit_study(split_part(name, '/', 1))
);

