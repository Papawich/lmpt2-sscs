-- LMPT2 SSCS cloud backend for Supabase
-- Run this file once in Supabase Dashboard > SQL Editor.
-- It creates Auth-linked profiles, vessel/study tables, RLS policies,
-- a private Storage bucket, and a small audit trail.

begin;

create extension if not exists pgcrypto;

-- ---------------------------------------------------------------------------
-- Core tables
-- ---------------------------------------------------------------------------
create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  full_name text not null default '',
  email text not null default '',
  company text not null default '',
  role text check (role in ('terminal_officer','ship_officer','viewer')),
  account_status text not null default 'pending' check (account_status in ('pending','approved','rejected')),
  is_admin boolean not null default false,
  registered_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create unique index if not exists profiles_email_lower_idx on public.profiles (lower(email));

create table if not exists public.vessels (
  id bigint primary key generated by default as identity,
  name text not null,
  imo text not null,
  call_sign text,
  flag text,
  port_of_registry text,
  year_built integer,
  vessel_type text,
  capacity text,
  owner text,
  operator text,
  classification text,
  gas_mgmt_1 text,
  gas_mgmt_2 text,
  status text not null default 'Active',
  created_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create unique index if not exists vessels_imo_lower_idx on public.vessels (lower(imo));
create index if not exists vessels_name_idx on public.vessels (name);

create table if not exists public.sscs_studies (
  id text primary key,
  vessel_id bigint not null references public.vessels(id) on delete restrict,
  vessel_name text not null,
  status text not null check (status in ('access_requested','access_rejected','draft','submitted','approved','edit_requested','editing')),
  initiated_by_id uuid not null references auth.users(id) on delete restrict,
  initiated_by_name text not null,
  initiated_by_role text check (initiated_by_role in ('terminal_officer','ship_officer','viewer')),
  initiated_at timestamptz not null default now(),
  submitted_at timestamptz,
  reviewed_by_id uuid references auth.users(id) on delete set null,
  reviewed_by_name text,
  approved_at timestamptz,
  edit_requested_by_id uuid references auth.users(id) on delete set null,
  edit_requested_by_name text,
  edit_requested_at timestamptz,
  items jsonb not null default '[]'::jsonb,
  ship_notes text not null default '',
  terminal_notes text not null default '',
  updated_at timestamptz not null default now()
);

create index if not exists sscs_studies_vessel_idx on public.sscs_studies(vessel_id);
create index if not exists sscs_studies_initiated_by_idx on public.sscs_studies(initiated_by_id);
create index if not exists sscs_studies_status_idx on public.sscs_studies(status);

create table if not exists public.study_sections (
  study_id text not null references public.sscs_studies(id) on delete cascade,
  section_key text not null,
  data jsonb not null default '{}'::jsonb,
  updated_by uuid references auth.users(id) on delete set null,
  updated_at timestamptz not null default now(),
  primary key (study_id, section_key)
);

create table if not exists public.documents (
  id uuid primary key default gen_random_uuid(),
  study_id text not null references public.sscs_studies(id) on delete cascade,
  document_type text not null,
  file_name text not null,
  storage_path text not null unique,
  mime_type text,
  file_size bigint,
  uploaded_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now()
);

create index if not exists documents_study_idx on public.documents(study_id);

create table if not exists public.audit_logs (
  id bigint primary key generated always as identity,
  user_id uuid references auth.users(id) on delete set null,
  action text not null,
  entity_type text not null,
  entity_id text,
  details jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create index if not exists audit_logs_created_idx on public.audit_logs(created_at desc);
create index if not exists audit_logs_entity_idx on public.audit_logs(entity_type, entity_id);

-- ---------------------------------------------------------------------------
-- Auth profile creation
-- ---------------------------------------------------------------------------
create or replace function public.handle_new_auth_user()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  requested_role text;
begin
  requested_role := new.raw_user_meta_data->>'role';
  if requested_role not in ('terminal_officer','ship_officer','viewer') then
    requested_role := 'viewer';
  end if;

  insert into public.profiles (
    id, full_name, email, company, role, account_status, is_admin, registered_at, updated_at
  ) values (
    new.id,
    coalesce(new.raw_user_meta_data->>'full_name', ''),
    coalesce(new.email, ''),
    coalesce(new.raw_user_meta_data->>'company', ''),
    requested_role,
    'pending',
    false,
    coalesce(new.created_at, now()),
    now()
  )
  on conflict (id) do update set
    full_name = excluded.full_name,
    email = excluded.email,
    company = excluded.company,
    role = excluded.role,
    updated_at = now();

  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
after insert on auth.users
for each row execute function public.handle_new_auth_user();

-- Backfill profiles if Auth users already existed before this migration.
insert into public.profiles (id, full_name, email, company, role, account_status, is_admin, registered_at, updated_at)
select
  u.id,
  coalesce(u.raw_user_meta_data->>'full_name',''),
  coalesce(u.email,''),
  coalesce(u.raw_user_meta_data->>'company',''),
  case when u.raw_user_meta_data->>'role' in ('terminal_officer','ship_officer','viewer')
       then u.raw_user_meta_data->>'role' else 'viewer' end,
  'pending',
  false,
  coalesce(u.created_at, now()),
  now()
from auth.users u
on conflict (id) do nothing;

-- ---------------------------------------------------------------------------
-- Security helper functions. SECURITY DEFINER avoids recursive profile RLS.
-- ---------------------------------------------------------------------------
create or replace function public.current_user_is_admin()
returns boolean
language sql
stable
security definer
set search_path = public, pg_temp
as $$
  select coalesce((select p.is_admin from public.profiles p where p.id = auth.uid()), false);
$$;

create or replace function public.current_user_is_approved()
returns boolean
language sql
stable
security definer
set search_path = public, pg_temp
as $$
  select coalesce((select p.account_status = 'approved' from public.profiles p where p.id = auth.uid()), false);
$$;

create or replace function public.current_user_role()
returns text
language sql
stable
security definer
set search_path = public, pg_temp
as $$
  select (select p.role from public.profiles p where p.id = auth.uid());
$$;

create or replace function public.can_read_study(target_study_id text)
returns boolean
language sql
stable
security definer
set search_path = public, pg_temp
as $$
  select public.current_user_is_approved()
     and exists (select 1 from public.sscs_studies s where s.id = target_study_id);
$$;

create or replace function public.can_edit_study(target_study_id text)
returns boolean
language sql
stable
security definer
set search_path = public, pg_temp
as $$
  select exists (
    select 1
    from public.sscs_studies s
    where s.id = target_study_id
      and public.current_user_is_approved()
      and (
        public.current_user_is_admin()
        or public.current_user_role() = 'terminal_officer'
        or (
          public.current_user_role() = 'ship_officer'
          and s.initiated_by_id = auth.uid()
          and s.status in ('draft','editing')
        )
      )
  );
$$;

