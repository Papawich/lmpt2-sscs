-- Profiles: users can always read themselves. Approved users can read the internal
-- directory because the application needs recipient names/emails for workflow notices.
drop policy if exists profiles_select on public.profiles;
create policy profiles_select on public.profiles
for select to authenticated
using (id = auth.uid() or public.current_user_is_approved() or public.current_user_is_admin());

drop policy if exists profiles_admin_update on public.profiles;
create policy profiles_admin_update on public.profiles
for update to authenticated
using (public.current_user_is_admin())
with check (public.current_user_is_admin());

-- Vessels
drop policy if exists vessels_select on public.vessels;
create policy vessels_select on public.vessels
for select to authenticated
using (public.current_user_is_approved() or public.current_user_is_admin());

drop policy if exists vessels_insert on public.vessels;
create policy vessels_insert on public.vessels
for insert to authenticated
with check (
  public.current_user_is_approved()
  and (
    public.current_user_is_admin()
    or public.current_user_role() in ('terminal_officer','ship_officer')
  )
  and (created_by is null or created_by = auth.uid())
);

drop policy if exists vessels_update on public.vessels;
create policy vessels_update on public.vessels
for update to authenticated
using (
  public.current_user_is_approved()
  and (
    public.current_user_is_admin()
    or public.current_user_role() = 'terminal_officer'
    or created_by = auth.uid()
  )
)
with check (
  public.current_user_is_approved()
  and (
    public.current_user_is_admin()
    or public.current_user_role() = 'terminal_officer'
    or created_by = auth.uid()
  )
);

drop policy if exists vessels_delete on public.vessels;
create policy vessels_delete on public.vessels
for delete to authenticated
using (public.current_user_is_admin());

-- Studies: all approved internal users may read. Viewer is read-only.
drop policy if exists studies_select on public.sscs_studies;
create policy studies_select on public.sscs_studies
for select to authenticated
using (public.current_user_is_approved() or public.current_user_is_admin());

